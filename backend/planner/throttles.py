# هدف: بستنِ سطحِ حمله‌ی «حدسِ رمزِ عبور» (Brute-force) روی مسیرهایِ
# احرازِ هویت. چرخش/ابطالِ توکنِ Refresh (2026-09-08) توکنِ دزدیده‌شده را
# بی‌اعتبار می‌کند، ولی کسی که دارد «رمز» را حدس می‌زند هنوز می‌تواند
# بی‌وقفه به login//register درخواست بزند — این کلاس آن فاصله را می‌بندد.
#
# چرا کلاسِ سفارشی و نه ScopedRateThrottleِ آماده؟ آن کلاس نرخ را از
# ویژگیِ view.throttle_scope می‌خواند (برایِ ViewSetها مناسب است)؛ این
# کلاس scope را خودش «auth» سفت کرده تا روی ویوهایِ تابعیِ register/login
# فقط با یک دیکوریتورِ @throttle_classes اعمال شود و نشود فراموشش کرد.
#
# نرخِ عددی از REST_FRAMEWORK['DEFAULT_THROTTLE_RATES']['auth'] خوانده
# می‌شود که از متغیرِ محیطیِ DJANGO_AUTH_THROTTLE_RATE می‌آید — پیش‌فرضِ
# توسعه 10000/min (مؤثراً نامحدود؛ بدونِ ست‌کردنِ هیچ متغیری رفتارِ
# محلی تغییر نمی‌کند — الگویِ dev-safeِ نکته‌ی ۶.۱۰ AI_CONTEXT) و
# پیشنهادِ Production مثل '20/min'.
# ----------------------------------------------------------------------------

from rest_framework.throttling import SimpleRateThrottle


class AuthBurstThrottle(SimpleRateThrottle):
    """محدودیتِ نرخِ ویژه‌ی مسیرهایِ احرازِ هویت (scope = 'auth').

    کلیدِ شمارش = هویتِ شبکه‌ی درخواست (IP) — مسیرهایِ register/login همیشه
    «بی‌احرازِ هویت» صدا زده می‌شوند (توکنی هنوز وجود ندارد)، پس شمارشِ
    «هر IP» معنایِ عملی دارد. پشتِ پروکسیِ Nginx، هدرِ X-Forwarded-For که
    Nginx با IP واقعیِ کاربر ست می‌کند به‌عنوانِ همان هویت استفاده می‌شود
    (رفتارِ خودِ DRF در get_ident).
    """

    scope = 'auth'

    def get_cache_key(self, request, view):
        # کلید مستقل از view ساخته می‌شود (scope سفت‌شده) — وابسته به
        # هیچ ویژگیِ view نیست تا روی هر دو نوعِ ویو (تابعی/کلاسی) یکسان
        # کار کند.
        return self.cache_format % {'scope': self.scope, 'ident': self.get_ident(request)}
